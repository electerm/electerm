/**
 * The module a widget's server script may load.
 *
 * `require('@electerm/widget-api')` has to work from a widget folder that was
 * copied in after the app shipped, so there is nothing to install: the loader
 * writes this shim into the widget's own node_modules before the entry is
 * required (see ./api.js). Real files, so the ordinary node resolver finds it —
 * CommonJS and ESM both, on the Electron 22 build and on the web server, with no
 * require hooks.
 *
 * Alongside it goes index.d.ts: the api is the host's, so the types ship with
 * the host too. A widget author gets completion while writing and the code that
 * runs is still the host's — there is no published package to fall out of sync
 * with the app that is actually running.
 *
 * The shim is per widget folder on purpose: node caches a module by its
 * resolved path, so a single shared file would be evaluated once for whichever
 * widget loaded first and every later widget would get that widget's api.
 */

const fs = require('fs')
const path = require('path')

const API_PACKAGE = '@electerm/widget-api'
const API_VERSION = '1.0.0'
// the same rule the rest of the widget loader uses for folder / scheme ids
const VALID_ID = /^[a-z0-9-]+$/

function apiModuleDir (widgetDir) {
  // '@electerm/widget-api' -> node_modules/@electerm/widget-api
  return path.join(widgetDir, 'node_modules', ...API_PACKAGE.split('/'))
}

function shimSource (id) {
  return `'use strict'
// Generated by electerm on every load, do not edit: the file is rewritten.
// The host installs __electermWidgetApiFactory before it requires any widget
// module, so this resolves to the api of this widget folder only.
var create = globalThis.__electermWidgetApiFactory
if (typeof create !== 'function') {
  throw new Error('${API_PACKAGE} can only be loaded inside electerm')
}
module.exports = create('${id}')
`
}

// Hand-written on purpose: it describes the contract, so it is edited with
// api.js, not generated from it.
const TYPES = `// Generated by electerm, do not edit: the file is rewritten on every load.
/** What a widget's server script may do, and what it may not. */
declare namespace widgetApi {
  interface Capabilities {
    css: boolean
    notify: boolean
    openExternal: boolean
    clipboard: boolean
    dialog: boolean
    secret: boolean
    net: boolean
  }
  interface Event {
    type: string
    ok?: boolean
    msg?: string
    from?: string
    [key: string]: unknown
  }
  interface WidgetApi {
    /** the widget id, i.e. its folder name and its electerm-widget:// host */
    readonly id: string
    /** false in the desktop app, true when the server is the web app */
    readonly isWebApp: boolean
    readonly platform: string
    /** what this host can actually do; check before calling a capability */
    readonly capabilities: Capabilities
    log (levelOrMessage: string, ...rest: unknown[]): void
    event (evt: Event): void
    css: {
      /** restyle the app; the host applies it in its own window */
      apply (css: string): string
      /** same, reading a file from the widget folder, e.g. 'style.css' */
      applyFile (rel: string): string
      remove (): string
      get (): string
    }
    notify (opts: { title?: string, message?: string } | string): void
    openExternal (url: string): Promise<void>
    clipboard: {
      read (): string
      write (text: string): void
    }
    dialog: {
      open (opts?: unknown): Promise<{ canceled: boolean, filePaths: string[] }>
      save (opts?: unknown): Promise<{ canceled: boolean, filePath?: string }>
    }
    secret: {
      /** false on a host without a keychain: do not ask the user for a secret */
      available (): boolean
      encrypt (text: string): string
      decrypt (data: string): string
    }
    net: {
      /** what the OS would use for this url, e.g. "PROXY 127.0.0.1:10808; DIRECT" */
      resolveProxy (url: string): Promise<string>
    }
  }
}
declare const api: widgetApi.WidgetApi
export = api
`

function packageSource () {
  return JSON.stringify({
    name: API_PACKAGE,
    version: API_VERSION,
    private: true,
    description: 'electerm widget api (generated shim)',
    main: 'index.js',
    types: 'index.d.ts'
  }, null, 2) + '\n'
}

function writeIfChanged (file, content) {
  try {
    if (fs.readFileSync(file, 'utf8') === content) {
      return
    }
  } catch (e) {}
  fs.mkdirSync(path.dirname(file), { recursive: true })
  fs.writeFileSync(file, content)
}

/**
 * Make `require('@electerm/widget-api')` resolve inside one widget folder.
 * Cheap and idempotent: normally both files are already there and only read.
 */
function ensureApiModule (widgetDir, id) {
  if (!VALID_ID.test(String(id))) {
    throw new Error(`invalid widget id for the api shim: ${id}`)
  }
  const dir = apiModuleDir(widgetDir)
  writeIfChanged(path.join(dir, 'package.json'), packageSource())
  writeIfChanged(path.join(dir, 'index.js'), shimSource(id))
  writeIfChanged(path.join(dir, 'index.d.ts'), TYPES)
  return dir
}

module.exports = {
  API_PACKAGE,
  API_VERSION,
  apiModuleDir,
  ensureApiModule,
  shimSource,
  TYPES
}
