const { test, expect, _electron: electron } = require('@playwright/test')
const appOptions = require('./common/app-options')

test('pausing keeps the scrolled view while the live buffer advances', async () => {
  const app = await electron.launch(appOptions)
  try {
    const page = await app.firstWindow()
    const button = page.locator('.terminal-view-button')
    await page.waitForFunction(() => window.refs?.get('term-' + window.store.activeTabId)?.attachAddon?.hasReceivedInitialData)
    const pane = await page.evaluateHandle(() => window.refs.get('term-' + window.store.activeTabId))
    await page.waitForFunction(p => !!p.onOutputActivity, pane)
    await expect(button).toHaveCount(0)
    await pane.evaluate(({ term }) => {
      term.options.scrollback = 500
      const lines = Array.from({ length: term.rows + 600 }, (_, i) => 'before pause ' + i)
      term.write(lines.join('\r\n') + '\r\n')
    })
    await pane.evaluate(p => p.attachAddon.writeToTerminal('one isolated line\r\n'))
    await expect(button).toHaveCount(0)
    // Feed bursts through the same receive/coalescing path used by a session.
    const startOutput = () => pane.evaluateHandle(p => setInterval(() => {
      p.attachAddon.writeToTerminal('before pause streaming\r\n')
    }, 90))
    const stream = await startOutput()
    await expect(button.locator('.anticon-loading')).toBeVisible()
    await stream.evaluate(id => clearInterval(id))
    await expect(button).toHaveCount(0)
    const nextStream = await startOutput()
    await expect(button.locator('.anticon-loading')).toBeVisible()
    await nextStream.evaluate(id => clearInterval(id))
    await page.evaluate(() => window.store.toggleTerminalSearch())
    await expect(page.locator('.term-search-wrap')).toBeVisible()
    const expectedLine = await pane.evaluate(({ term }) => {
      term.scrollToLine(250)
      return term.buffer.active.getLine(250).translateToString(true)
    })
    await button.click()
    await expect(button).toHaveAttribute('aria-pressed', 'true')
    await expect(page.locator('.term-search-wrap')).toHaveCount(0)
    const readPausedRow = () => pane.evaluate(p => {
      const buffer = p.pausedTerm.buffer.active
      return buffer.getLine(buffer.viewportY).translateToString(true)
    })
    await expect.poll(readPausedRow).toBe(expectedLine)
    expect(await pane.evaluate(p => p.pausedTerm.buffer.active.length <= 4 * p.term.rows)).toBe(true)
    const line = await readPausedRow()
    expect(line).toContain('before pause')
    await pane.evaluate(({ term }) => term.write('new output\r\n'.repeat(term.rows + 600)))
    await expect.poll(() => pane.evaluate(p => p.term.buffer.active.getLine(5).translateToString(true))).toBe('new output')
    expect(await readPausedRow()).toBe(line)
    await pane.evaluate(p => p.pausedTerm.select(0, p.pausedTerm.buffer.active.viewportY, 'before pause'.length))
    expect(await pane.evaluate(p => p.getVisibleTerminal().getSelection())).toBe('before pause')

    const tabId = await pane.evaluate(p => p.props.tab.id)
    await page.evaluate(() => window.store.addTab())
    await expect(button).toHaveCount(0)
    await page.locator(`.tabs .tab[data-id="${tabId}"]`).click()
    await expect(button).toHaveAttribute('aria-pressed', 'true')
    expect(await readPausedRow()).toBe(line)
    // The menu resume updates the footer through the pane's pause subscription.
    const pausedView = page.locator('.terminal-paused-view')
    await pausedView.click({ button: 'right', position: { x: 15, y: 15 } })
    const resume = await page.evaluate(() => window.translate('resume'))
    await page.getByRole('menu').getByText(resume, { exact: true }).click({ timeout: 4000 })
    await expect(button).toHaveCount(0)
    await expect(page.locator('.terminal-paused-view')).toHaveCount(0)
    expect(await pane.evaluate(({ term }) => term.buffer.active.viewportY === term.buffer.active.baseY)).toBe(true)
    await pane.evaluate(p => p.term.write('\x1b[?1049h\x1b[Halternate screen'))
    await expect.poll(() => pane.evaluate(p => p.term.buffer.active.type)).toBe('alternate')
    await pane.evaluate(p => p.setViewPaused(true))
    await expect.poll(() => pane.evaluate(p => p.pausedTerm?.buffer.active.getLine(0)?.translateToString(true))).toBe('alternate screen')
    await expect(button).toHaveAttribute('aria-pressed', 'true')
    await pane.evaluate(p => p.zoom(1))
    await expect.poll(() => pane.evaluate(p => p.pausedTerm.options.fontSize === p.term.options.fontSize)).toBe(true)
    await pane.evaluate(p => p.socket.close())
    await expect(page.locator('.terminal-paused-view')).toHaveCount(0)
    await expect(button).toHaveCount(0)
  } finally {
    await app.close()
  }
})
